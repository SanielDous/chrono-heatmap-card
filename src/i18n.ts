export const TRANSLATIONS: Record<string, Dict> = { en, de, fr, nl, es, it, pl, sv };

export function resolveLanguage(lang: string | undefined): string {
  const base = (lang ?? 'en').trim().toLowerCase().split(/[-_]/)[0];
  return Object.hasOwn(TRANSLATIONS, base) ? base : 'en';
}

export function localize(
  lang: string | undefined,
  key: string,
  params: Record<string, string | number> = {},
): string {
  const dict = TRANSLATIONS[resolveLanguage(lang)];
  const template = dict[key] ?? en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (m, name: string) => (name in params ? String(params[name]) : m));
}
